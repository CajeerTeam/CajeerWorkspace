-- Public Book reader bindings, immutable documentation collections, independent review and release pins.
CREATE TABLE book_sources (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL,
 project_id BIGINT NOT NULL,
 connection_key TEXT NOT NULL,
 config_hash TEXT NOT NULL CHECK(length(config_hash)=64),
 scope TEXT NOT NULL,
 name TEXT NOT NULL,
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
 created_by BIGINT NOT NULL REFERENCES users(id),
 created_at BIGINT NOT NULL,
 UNIQUE(project_id,connection_key,scope), UNIQUE(project_id,id),
 FOREIGN KEY(organization_id,project_id) REFERENCES projects(organization_id,id)
);
CREATE TABLE book_editions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL,
 source_id BIGINT NOT NULL,
 title TEXT NOT NULL,
 snapshot TEXT NOT NULL,
 snapshot_hash TEXT NOT NULL CHECK(length(snapshot_hash)=64),
 selection_hash TEXT NOT NULL CHECK(length(selection_hash)=64),
 author_id BIGINT NOT NULL REFERENCES users(id),
 reviewer_a BIGINT NOT NULL REFERENCES users(id),
 reviewer_b BIGINT NOT NULL REFERENCES users(id),
 request_key TEXT NOT NULL CHECK(length(request_key)=32),
 created_at BIGINT NOT NULL,
 UNIQUE(project_id,request_key), UNIQUE(project_id,id), UNIQUE(project_id,source_id,id),
 FOREIGN KEY(project_id,source_id) REFERENCES book_sources(project_id,id),
 CHECK(author_id<>reviewer_a AND author_id<>reviewer_b AND reviewer_a<>reviewer_b)
);
CREATE TABLE book_reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL,
 edition_id BIGINT NOT NULL,
 reviewer_id BIGINT NOT NULL REFERENCES users(id),
 decision TEXT NOT NULL CHECK(decision IN ('approve','changes')),
 note TEXT NOT NULL CHECK(length(note)>0),
 snapshot_hash TEXT NOT NULL CHECK(length(snapshot_hash)=64),
 created_at BIGINT NOT NULL,
 UNIQUE(edition_id,reviewer_id),
 FOREIGN KEY(project_id,edition_id) REFERENCES book_editions(project_id,id)
);
CREATE TABLE book_release_links (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL,
 release_id BIGINT NOT NULL,
 source_id BIGINT NOT NULL,
 edition_id BIGINT NOT NULL,
 tag TEXT NOT NULL,
 commit_sha TEXT NOT NULL CHECK(length(commit_sha)=40),
 release_hash TEXT NOT NULL CHECK(length(release_hash)=64),
 snapshot_hash TEXT NOT NULL CHECK(length(snapshot_hash)=64),
 linked_by BIGINT NOT NULL REFERENCES users(id),
 linked_at BIGINT NOT NULL,
 UNIQUE(release_id,source_id),
 FOREIGN KEY(project_id,source_id,edition_id) REFERENCES book_editions(project_id,source_id,id),
 FOREIGN KEY(release_id,project_id) REFERENCES project_releases(id,project_id)
);
CREATE INDEX book_sources_project ON book_sources(project_id,id);
CREATE INDEX book_editions_source ON book_editions(project_id,source_id,id);
CREATE INDEX book_release_links_edition ON book_release_links(project_id,edition_id);
