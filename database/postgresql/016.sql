-- Paired entries are balanced by construction: a single positive amount on both sides.
CREATE TABLE accounting_accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organizations(id),
 code TEXT NOT NULL CHECK(length(code) BETWEEN 1 AND 20), name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 180),
 kind TEXT NOT NULL CHECK(kind IN ('asset','liability','equity','income','expense')),
 UNIQUE(organization_id,id), UNIQUE(organization_id,code)
);
CREATE TABLE accounting_periods (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organizations(id),
 starts_on TEXT NOT NULL, ends_on TEXT NOT NULL, closed_by BIGINT REFERENCES users(id), closed_at BIGINT,
 UNIQUE(organization_id,id), UNIQUE(organization_id,starts_on), CHECK(starts_on<=ends_on),
 CHECK((closed_by IS NULL AND closed_at IS NULL) OR (closed_by IS NOT NULL AND closed_at IS NOT NULL))
);
CREATE TABLE accounting_openings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL UNIQUE, period_id BIGINT NOT NULL,
 prepared_by BIGINT NOT NULL REFERENCES users(id), prepared_at BIGINT NOT NULL,
 cash_digest TEXT NOT NULL CHECK(length(cash_digest)=64), cash_count BIGINT NOT NULL CHECK(cash_count>=0),
 snapshot TEXT NOT NULL, pairs TEXT NOT NULL, expected TEXT NOT NULL, evidence TEXT NOT NULL,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0), approved_by BIGINT REFERENCES users(id), approved_at BIGINT, review_note TEXT,
 FOREIGN KEY(organization_id,period_id) REFERENCES accounting_periods(organization_id,id),
 CHECK((approved_by IS NULL AND approved_at IS NULL AND review_note IS NULL) OR (approved_by IS NOT NULL AND approved_by<>prepared_by AND approved_at IS NOT NULL AND review_note IS NOT NULL))
);
CREATE UNIQUE INDEX cash_project_identity_accounting ON cash_entries(project_id,id);
CREATE TABLE accounting_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL, period_id BIGINT NOT NULL, project_id BIGINT,
 booked_on TEXT NOT NULL, currency TEXT NOT NULL CHECK(currency IN ('RUB','EUR','USD','PLN','GBP')),
 debit_id BIGINT NOT NULL, credit_id BIGINT NOT NULL, amount_minor BIGINT NOT NULL CHECK(amount_minor BETWEEN 1 AND 99999999999),
 kind TEXT NOT NULL CHECK(kind IN ('opening','cash','manual','reversal')), memo TEXT NOT NULL CHECK(length(memo) BETWEEN 1 AND 500),
 cash_id BIGINT UNIQUE, reversal_of BIGINT UNIQUE, actor_id BIGINT NOT NULL REFERENCES users(id), created_at BIGINT NOT NULL,
 UNIQUE(organization_id,id), CHECK(debit_id<>credit_id),
 FOREIGN KEY(organization_id,period_id) REFERENCES accounting_periods(organization_id,id),
 FOREIGN KEY(organization_id,project_id) REFERENCES projects(organization_id,id),
 FOREIGN KEY(organization_id,debit_id) REFERENCES accounting_accounts(organization_id,id),
 FOREIGN KEY(organization_id,credit_id) REFERENCES accounting_accounts(organization_id,id),
 FOREIGN KEY(project_id,cash_id) REFERENCES cash_entries(project_id,id),
 FOREIGN KEY(organization_id,reversal_of) REFERENCES accounting_entries(organization_id,id),
 CHECK((kind='cash' AND cash_id IS NOT NULL AND project_id IS NOT NULL) OR (kind<>'cash' AND cash_id IS NULL)),
 CHECK((kind='reversal' AND reversal_of IS NOT NULL) OR kind='cash' OR (kind IN ('opening','manual') AND reversal_of IS NULL)),
 CHECK(kind<>'opening' OR project_id IS NULL)
);
CREATE INDEX accounting_entry_period ON accounting_entries(organization_id,booked_on,id);
