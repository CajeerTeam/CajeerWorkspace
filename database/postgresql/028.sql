-- Editorial release coordination: native publication and forum receipts stay authoritative.
CREATE UNIQUE INDEX editorial_engine_project_id ON engine_publications(project_id,id);
CREATE UNIQUE INDEX editorial_book_link_project_id ON book_release_links(project_id,id,release_id,edition_id);
CREATE TABLE editorial_releases (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL,
 release_id BIGINT NOT NULL,
 book_link_id BIGINT NOT NULL,
 edition_id BIGINT NOT NULL,
 page_key TEXT NOT NULL,
 page_hash TEXT NOT NULL CHECK(length(page_hash)=64),
 snapshot_hash TEXT NOT NULL CHECK(length(snapshot_hash)=64),
 engine_publication_id BIGINT,
 engine_field TEXT,
 lite_site_id BIGINT,
 lite_path TEXT,
 lite_hash TEXT CHECK(lite_hash IS NULL OR length(lite_hash)=64),
 forum_source_id BIGINT NOT NULL,
 actor_id BIGINT NOT NULL REFERENCES users(id),
 request_key TEXT NOT NULL CHECK(length(request_key)=32),
 plan_hash TEXT NOT NULL CHECK(length(plan_hash)=64),
 workspace_origin TEXT,
 forum_key TEXT NOT NULL CHECK(length(forum_key)=32),
 forum_attempt BIGINT NOT NULL DEFAULT 1 CHECK(forum_attempt>0),
 cms_url TEXT,
 cms_confirmed_at BIGINT,
 created_at BIGINT NOT NULL,
 abandoned_at BIGINT,
 UNIQUE(project_id,id), UNIQUE(project_id,request_key), UNIQUE(engine_publication_id),
 FOREIGN KEY(release_id,project_id) REFERENCES project_releases(id,project_id),
 FOREIGN KEY(project_id,book_link_id,release_id,edition_id) REFERENCES book_release_links(project_id,id,release_id,edition_id),
 FOREIGN KEY(project_id,edition_id) REFERENCES book_editions(project_id,id),
 FOREIGN KEY(project_id,engine_publication_id) REFERENCES engine_publications(project_id,id),
 FOREIGN KEY(project_id,lite_site_id) REFERENCES lite_sites(project_id,id),
 FOREIGN KEY(project_id,forum_source_id) REFERENCES forum_sources(project_id,id),
 CHECK((engine_publication_id IS NOT NULL AND engine_field IS NOT NULL AND lite_site_id IS NULL AND lite_path IS NULL AND lite_hash IS NULL) OR (engine_publication_id IS NULL AND engine_field IS NULL AND lite_site_id IS NOT NULL AND lite_path IS NOT NULL AND lite_hash IS NOT NULL)),
 CHECK((cms_url IS NULL AND cms_confirmed_at IS NULL) OR (cms_url IS NOT NULL AND cms_confirmed_at IS NOT NULL))
);
CREATE TABLE editorial_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL,
 editorial_id BIGINT NOT NULL,
 actor_id BIGINT NOT NULL REFERENCES users(id),
 step TEXT NOT NULL CHECK(step IN ('book','cms','forum')),
 state TEXT NOT NULL,
 detail TEXT NOT NULL DEFAULT '',
 created_at BIGINT NOT NULL,
 FOREIGN KEY(project_id,editorial_id) REFERENCES editorial_releases(project_id,id)
);
CREATE UNIQUE INDEX editorial_active_release ON editorial_releases(release_id,forum_source_id) WHERE abandoned_at IS NULL;
CREATE INDEX editorial_project ON editorial_releases(project_id,id);
CREATE INDEX editorial_events_run ON editorial_events(editorial_id,id);
