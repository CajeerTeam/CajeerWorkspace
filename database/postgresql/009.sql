CREATE TABLE counterparties (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL REFERENCES organizations(id),
 name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 180), registration TEXT NOT NULL DEFAULT '', notes TEXT NOT NULL DEFAULT '',
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0), UNIQUE(organization_id,id)
);
CREATE TABLE counterparty_contacts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL, counterparty_id BIGINT NOT NULL,
 name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 180), email TEXT NOT NULL, phone TEXT NOT NULL DEFAULT '',
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0), UNIQUE(organization_id,counterparty_id,id), UNIQUE(counterparty_id,email),
 FOREIGN KEY(organization_id,counterparty_id) REFERENCES counterparties(organization_id,id)
);
CREATE TABLE client_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, organization_id BIGINT NOT NULL, project_id BIGINT NOT NULL, counterparty_id BIGINT NOT NULL, contact_id BIGINT NOT NULL,
 title TEXT NOT NULL CHECK(length(title) BETWEEN 1 AND 180), request_text TEXT NOT NULL CHECK(length(request_text) BETWEEN 1 AND 4000),
 client_name TEXT NOT NULL, contact_name TEXT NOT NULL, contact_email TEXT NOT NULL,
 created_by BIGINT NOT NULL REFERENCES users(id), created_at BIGINT NOT NULL,
 UNIQUE(project_id,id), FOREIGN KEY(organization_id,project_id) REFERENCES projects(organization_id,id),
 FOREIGN KEY(organization_id,counterparty_id,contact_id) REFERENCES counterparty_contacts(organization_id,counterparty_id,id)
);
CREATE INDEX client_orders_org ON client_orders(organization_id,id);
CREATE TABLE client_offers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES client_orders(id), revision BIGINT NOT NULL CHECK(revision>0),
 scope TEXT NOT NULL CHECK(length(scope) BETWEEN 1 AND 4000), currency TEXT NOT NULL CHECK(currency IN ('RUB','EUR','USD','PLN','GBP')),
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','offered','accepted','rejected')), version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 offered_at BIGINT, decided_at BIGINT, decided_guest BIGINT REFERENCES guest_invites(id), decision_note TEXT NOT NULL DEFAULT '',
 UNIQUE(order_id,revision), UNIQUE(order_id,id),
 CHECK((status='draft' AND offered_at IS NULL) OR (status<>'draft' AND offered_at IS NOT NULL)),
 CHECK((status IN ('draft','offered') AND decided_at IS NULL AND decided_guest IS NULL) OR (status IN ('accepted','rejected') AND decided_at IS NOT NULL AND decided_guest IS NOT NULL))
);
CREATE UNIQUE INDEX client_offer_open ON client_offers(order_id) WHERE status IN ('draft','offered','accepted');
CREATE TABLE client_stages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL, offer_id BIGINT NOT NULL, project_id BIGINT NOT NULL,
 title TEXT NOT NULL CHECK(length(title) BETWEEN 1 AND 180), scope TEXT NOT NULL CHECK(length(scope) BETWEEN 1 AND 4000), due_on TEXT NOT NULL,
 amount_minor BIGINT NOT NULL CHECK(amount_minor BETWEEN 1 AND 99999999999),
 UNIQUE(project_id,id), FOREIGN KEY(order_id,offer_id) REFERENCES client_offers(order_id,id), FOREIGN KEY(project_id,order_id) REFERENCES client_orders(project_id,id)
);
CREATE INDEX client_stages_offer ON client_stages(offer_id,id);
CREATE TABLE client_stage_tasks (
 stage_id BIGINT NOT NULL, project_id BIGINT NOT NULL, task_id BIGINT NOT NULL UNIQUE,
 PRIMARY KEY(stage_id,task_id), FOREIGN KEY(project_id,stage_id) REFERENCES client_stages(project_id,id), FOREIGN KEY(project_id,task_id) REFERENCES tasks(project_id,id)
);
CREATE UNIQUE INDEX guest_invites_project_id ON guest_invites(project_id,id);
CREATE TABLE client_order_guests (
 guest_id BIGINT PRIMARY KEY, project_id BIGINT NOT NULL, order_id BIGINT NOT NULL,
 FOREIGN KEY(project_id,guest_id) REFERENCES guest_invites(project_id,id), FOREIGN KEY(project_id,order_id) REFERENCES client_orders(project_id,id)
);
CREATE TABLE client_deliveries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, stage_id BIGINT NOT NULL, project_id BIGINT NOT NULL, revision BIGINT NOT NULL CHECK(revision>0),
 result_text TEXT NOT NULL CHECK(length(result_text) BETWEEN 1 AND 4000), document_id BIGINT, document_revision BIGINT,
 submitted_by BIGINT NOT NULL REFERENCES users(id), submitted_at BIGINT NOT NULL,
 status TEXT NOT NULL DEFAULT 'submitted' CHECK(status IN ('submitted','accepted','returned')),
 decided_guest BIGINT REFERENCES guest_invites(id), decided_at BIGINT, decision_note TEXT NOT NULL DEFAULT '',
 accepted_minutes BIGINT CHECK(accepted_minutes IS NULL OR (accepted_minutes>=0)),
 UNIQUE(stage_id,revision), UNIQUE(stage_id,id), FOREIGN KEY(project_id,stage_id) REFERENCES client_stages(project_id,id),
 FOREIGN KEY(project_id,document_id) REFERENCES documents(project_id,id), FOREIGN KEY(document_id,document_revision) REFERENCES document_versions(document_id,revision),
 CHECK((document_id IS NULL AND document_revision IS NULL) OR (document_id IS NOT NULL AND document_revision IS NOT NULL)),
 CHECK((status='submitted' AND decided_guest IS NULL AND decided_at IS NULL) OR (status<>'submitted' AND decided_guest IS NOT NULL AND decided_at IS NOT NULL)),
 CHECK((status='accepted' AND accepted_minutes IS NOT NULL) OR (status<>'accepted' AND accepted_minutes IS NULL))
);
CREATE UNIQUE INDEX client_delivery_open ON client_deliveries(stage_id) WHERE status IN ('submitted','accepted');
CREATE TABLE client_stage_hours (
 delivery_id BIGINT NOT NULL REFERENCES client_deliveries(id), entry_id BIGINT NOT NULL UNIQUE REFERENCES time_entries(id),
 minutes BIGINT NOT NULL CHECK(minutes BETWEEN 1 AND 1440), PRIMARY KEY(delivery_id,entry_id)
);
